"""Generate rp1210_codes.h from the MIT-licensed RP1210 reference library.

Transcribing 100+ error codes and 30+ command ids by hand is how you get a driver that returns the
wrong code for the wrong condition. dfieschko/RP1210 (MIT, Copyright (c) 2021 Darius Fieschko) has
them all as Python dicts, so they are read from there instead. See NOTICE.md.

Usage: python gen_rp1210_codes.py <path-to-RP1210-main> [-o rp1210_codes.h]
"""

import argparse
import ast
import os
import sys


def read_dict(path, name):
    """Pulls a module-level dict literal out of a Python source file without importing it."""
    tree = ast.parse(open(path, encoding="utf-8").read())

    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if isinstance(target, ast.Name) and target.id == name:
                return ast.literal_eval(node.value)

    raise SystemExit(f"{name} not found in {path}")


def emit(errors, commands):
    out = []
    out.append("/* Generated by gen_rp1210_codes.py from dfieschko/RP1210 (MIT). Do not edit. */")
    out.append("#ifndef CANSUB_RP1210_CODES_H")
    out.append("#define CANSUB_RP1210_CODES_H")
    out.append("")
    out.append("/* Success. RP1210E section 16.4: a call returns 0 on success, and error codes are")
    out.append(" * greater than 127. Note the reference library maps 1 to NO_ERRORS, which disagrees")
    out.append(" * with the specification; codes below 128 are skipped below for that reason. */")
    out.append("#define RP1210_NO_ERRORS 0")
    out.append("")

    out.append("/* Error codes returned by the API. */")
    for code, name in sorted(errors.items()):
        if code < 128:
            continue
        out.append(f"#define {name:<44} {code}")

    out.append("")
    out.append("/* RP1210_SendCommand command numbers. */")
    for name, number in sorted(commands.items(), key=lambda kv: kv[1]):
        out.append(f"#define RPCMD_{name:<38} {number}")

    out.append("")
    out.append("/* Error-code to name mapping, for RP1210_GetErrorMsg. */")
    out.append("typedef struct")
    out.append("{")
    out.append("    short code;")
    out.append("    const char *text;")
    out.append("} rp1210_error_text_t;")
    out.append("")
    out.append(f"#define RP1210_ERROR_COUNT {len([c for c in errors if c >= 128])}")
    out.append("")
    out.append("/* The table is a C translation unit, so keep the name unmangled for C++ callers. */")
    out.append("#ifdef __cplusplus")
    out.append('extern "C" {')
    out.append("#endif")
    out.append("extern const rp1210_error_text_t rp1210_error_texts[RP1210_ERROR_COUNT];")
    out.append("#ifdef __cplusplus")
    out.append("}")
    out.append("#endif")
    out.append("")
    out.append("#endif")

    return "\n".join(out) + "\n"


def emit_table(errors):
    out = []
    out.append("/* Generated by gen_rp1210_codes.py from dfieschko/RP1210 (MIT). Do not edit. */")
    out.append('#include "rp1210_codes.h"')
    out.append("")
    out.append("const rp1210_error_text_t rp1210_error_texts[RP1210_ERROR_COUNT] = {")

    for code, name in sorted(errors.items()):
        if code < 128:
            continue
        out.append(f'    {{{code}, "{name}"}},')

    out.append("};")

    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("repo", help="path to the RP1210-main checkout")
    ap.add_argument("-o", "--output", default="rp1210_codes.h")
    args = ap.parse_args()

    rp1210_py = os.path.join(args.repo, "RP1210", "RP1210.py")
    commands_py = os.path.join(args.repo, "RP1210", "Commands.py")

    for path in (rp1210_py, commands_py):
        if not os.path.isfile(path):
            sys.exit(f"not found: {path}")

    errors = read_dict(rp1210_py, "RP1210_ERRORS")
    commands = read_dict(commands_py, "COMMAND_IDS")

    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write(emit(errors, commands))

    table = args.output.replace(".h", ".c")
    with open(table, "w", encoding="utf-8") as fh:
        fh.write(emit_table(errors))

    print(f"{len(errors)} error codes, {len(commands)} commands -> {args.output} + {table}",
          file=sys.stderr)


if __name__ == "__main__":
    main()
